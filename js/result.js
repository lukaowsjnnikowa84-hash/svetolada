function generatePDF() {
  console.log("📄 Начинаем генерацию PDF...");

  const btn = document.getElementById("downloadBtn");
  if (!btn) {
    console.error("❌ Кнопка скачивания не найдена!");
    return;
  }

  const originalText = btn.innerHTML;
  btn.innerHTML = "⏳ Подготовка PDF...";
  btn.disabled = true;
  btn.style.opacity = "0.7";

  const content = document.getElementById("reportContent");
  if (!content) {
    console.error("❌ Контент для PDF не найден!");
    btn.innerHTML = originalText;
    btn.disabled = false;
    btn.style.opacity = "1";
    return;
  }

  if (typeof html2pdf === "undefined") {
    console.error("❌ Библиотека html2pdf не загружена!");
    btn.innerHTML = "❌ Ошибка библиотеки";
    btn.disabled = false;
    btn.style.opacity = "1";
    alert("Библиотека для PDF не загружена. Проверьте подключение скриптов.");
    return;
  }

  let userName = "Пользователь";
  try {
    const data = JSON.parse(localStorage.getItem("cosmicReport"));
    if (data && data.user && data.user.name) {
      userName = data.user.name;
    }
  } catch (e) {}

  const scrollY = window.scrollY;
  window.scrollTo(0, 0);

  const opt = {
    margin: [15, 15, 15, 15],
    filename: `Космический_портрет_${userName.replace(/\s+/g, "_")}.pdf`,
    image: { type: "jpeg", quality: 0.98 },
    html2canvas: {
      scale: 2,
      useCORS: true,
      backgroundColor: "#0a0a1a",
      logging: false,
      windowWidth: content.scrollWidth || 1200,
      windowHeight: content.scrollHeight + 300 || 2200,
      width: content.scrollWidth || 1200,
      height: content.scrollHeight + 300 || 2200,
      x: 0,
      y: 0,
      onclone: function (doc) {
        const elements = doc.querySelectorAll(
          ".report-actions, .heart-message, .report-footer, #stars-container",
        );
        elements.forEach((el) => (el.style.display = "none"));
      },
    },
    jsPDF: {
      unit: "mm",
      format: "a4",
      orientation: "portrait",
    },
    pagebreak: {
      mode: ["css", "legacy"],
    },
  };

  setTimeout(function () {
    html2pdf()
      .set(opt)
      .from(content)
      .save()
      .then(function () {
        btn.innerHTML = originalText;
        btn.disabled = false;
        btn.style.opacity = "1";
        window.scrollTo(0, scrollY);
        console.log("✅ PDF успешно скачан!");
      })
      .catch(function (error) {
        console.error("❌ Ошибка при генерации PDF:", error);
        btn.innerHTML = "❌ Ошибка, попробуйте ещё раз";
        btn.disabled = false;
        btn.style.opacity = "1";
        window.scrollTo(0, scrollY);
        alert("Произошла ошибка при создании PDF. Попробуйте ещё раз.");
      });
  }, 600);
}

const downloadBtn = document.getElementById("downloadBtn");
if (downloadBtn) {
  downloadBtn.addEventListener("click", generatePDF);
  console.log("✅ PDF-генерация готова!");
} else {
  console.warn('⚠️ Кнопка "Скачать PDF" не найдена в HTML.');
}
