  function reduceNumber(num) {
    if (num === 0) return 0;
    while (num > 9 && num !== 11 && num !== 22 && num !== 33) {
      num = String(num)
        .split("")
        .reduce((sum, digit) => sum + parseInt(digit), 0);
    }
    return num;
  }

  function getLifePathNumber(birthDate) {
    const digits = birthDate
      .replace(/[^0-9]/g, "")
      .split("")
      .map(Number);
    return reduceNumber(digits.reduce((a, b) => a + b, 0));
  }

