function getHealthProfile(birthDate) {
  const day = parseInt(birthDate.split(/[.-]/)[0]);
  const month = parseInt(birthDate.split(/[.-]/)[1]);
  const year = parseInt(birthDate.split(/[.-]/)[2]);

  const lifePath = getLifePathNumber(birthDate);
  const psychomatrix = calculatePsychomatrix(birthDate);

  // Слабые системы органов по числу дня рождения
  const weakSystems = getWeakSystems(day);

  // Энергетический потенциал (по числу 2 в психоматрице)
  const energyLevel = psychomatrix.counts[2] || 0;

  // Склонность к заболеваниям
  const tendencies = getDiseaseTendencies(lifePath, month);

  // Рекомендации
  const recommendations = getHealthRecommendations(
    lifePath,
    weakSystems,
    energyLevel,
  );

  return {
    weakSystems,
    energyLevel:
      energyLevel >= 4
        ? "Высокая энергетика"
        : energyLevel >= 2
          ? "Средняя"
          : "Низкая, нужна подпитка",
    tendencies,
    recommendations,
    // Подробный блок для отчёта
    detailed: {
      "Слабые места": weakSystems.join(", "),
      Энергетика:
        energyLevel >= 4
          ? "🟢 Отличная"
          : energyLevel >= 2
            ? "🟡 Средняя"
            : "🔴 Слабая",
      "Склонность к": tendencies.join(", "),
      Рекомендации: recommendations.join(", "),
    },
  };
}

