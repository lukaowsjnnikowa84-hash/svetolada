function getDiseaseTendencies(lifePath, month) {
  const baseTendencies = {
    1: ["Сердечно-сосудистые", "Давление"],
    2: ["Простуды", "Инфекции"],
    3: ["Нервные расстройства", "Бессонница"],
    4: ["Желудочно-кишечные", "Ожирение"],
    5: ["Травмы", "Переломы"],
    6: ["Проблемы с кожей", "Аллергии"],
    7: ["Психосоматика", "Депрессии"],
    8: ["Токсины", "Печень"],
    9: ["Суставы", "Позвоночник"],
    11: ["Нервная система", "Стрессы"],
    22: ["Эндокринные", "Гормональные"],
  };

  const additional =
    month % 3 === 0
      ? ["Эмоциональное выгорание"]
      : month % 3 === 1
        ? ["Нарушение обмена"]
        : ["Ослабленный иммунитет"];

  return [...(baseTendencies[lifePath] || ["Общие"]), ...additional];
}

function getHealthRecommendations(lifePath, weakSystems, energyLevel) {
  const recs = [];

  if (energyLevel < 2) {
    recs.push("Принимать энергетические практики (цигун, йога)");
    recs.push("Избегать энергетических вампиров");
  }

  if (weakSystems.includes("Давление")) {
    recs.push("Контролировать давление, избегать стрессов");
  }

  if (weakSystems.includes("Пищеварение")) {
    recs.push("Правильное питание, режим, избегать жирного");
  }

  if (weakSystems.includes("Нервы")) {
    recs.push("Медитация, расслабление, ограничение кофеина");
  }

  // Общие рекомендации по жизненному пути
  const general = {
    1: "Умеренные физические нагрузки, контроль сердца",
    2: "Закаливание, укрепление иммунитета",
    3: "Сон, регулярность, успокаивающие практики",
    4: "Диета, физическая активность, детокс",
    5: "Осторожность в спорте, избегать травм",
    6: "Водные процедуры, уход за кожей",
    7: "Психотерапия, медитации, отдых",
    8: "Очищение организма, детокс-программы",
    9: "Укрепление спины, плавание",
    11: "Баланс активность-отдых, йога",
    22: "Гормональный баланс, эндокринолог",
  };

  if (general[lifePath]) {
    recs.push(general[lifePath]);
  }

  return recs.slice(0, 5);
}

